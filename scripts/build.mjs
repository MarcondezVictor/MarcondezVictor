// Builds dark_mode.svg and light_mode.svg: a neofetch-style profile card.
// Info block with live GitHub stats, sized to stay readable in the profile column.
//
// Usage: GH_TOKEN=<token> node scripts/build.mjs
// Runs daily in .github/workflows/build.yml. Node 20+, no dependencies.

import { writeFileSync } from 'node:fs';

const USER = 'MarcondezVictor';
const BIRTH = new Date(Date.UTC(2004, 9, 30)); // 30 Oct 2004
const TOKEN = process.env.GH_TOKEN || process.env.GITHUB_TOKEN;

const WIDTH = 56; // characters per info line
const FONT_SIZE = 18; // px
const CHAR_W = FONT_SIZE * 0.55; // approx. width of one monospace character
const LINE_H = Math.round(FONT_SIZE * 1.3);
const PAD = 28;

// ---------------------------------------------------------------- stats

async function gh(path, body) {
  const res = await fetch(`https://api.github.com${path}`, {
    method: body ? 'POST' : 'GET',
    headers: {
      Authorization: `bearer ${TOKEN}`,
      'Content-Type': 'application/json',
      'User-Agent': 'profile-card-builder',
    },
    body: body && JSON.stringify(body),
  });
  return { status: res.status, json: res.status === 204 ? null : await res.json() };
}

async function graphql(query, variables = {}) {
  const { json } = await gh('/graphql', { query, variables });
  if (json.errors) throw new Error(JSON.stringify(json.errors));
  return json.data;
}

// ---------------------------------------------------------------- lines of code
//
// Counts only hand-written code. GitHub's contributor stats only give weekly
// totals per repo, so they can't be filtered by file. Instead we walk every
// non-merge commit authored by USER on each repo's default branch and sum the
// per-file additions/deletions from the commit endpoint, keeping only files
// that pass isOwnCode().

const CODE_EXTENSIONS = new Set([
  'ts', 'tsx', 'js', 'jsx', 'mjs', 'java', 'cs', 'kt', 'c', 'h', 'py', 'php', 'sql', 'css', 'html',
]);

const EXCLUDED_PATHS = [
  /(^|\/)(node_modules|dist|build|out|\.next|coverage)\//, // build output and dependencies
  /(^|\/)types\/generated\//, // Strapi generated types
  /(^|\/)documentation\//, // Strapi generated API docs
  /\.min\.js$/, // minified bundles
  /(^|\/)(Packages|ProjectSettings|Library|Temp)\//, // Unity engine and editor folders
  /(^|\/)Assets\/TextMesh Pro\//, // Unity package imported into Assets
  /(^|\/)Assets\/TutorialInfo\//, // sample scripts from the Unity project template
  /(^|\/)\.(idea|vscode)\//, // editor configuration
  /(^|\/)database\.types\.ts$/, // generated by the Supabase CLI
  /(^|\/)fixtures\//, // test data
  /(^|\/)seed[^/]*\.sql$/, // seed data
];

// Data-only files written in a code language (country datasets, row updates).
// Listed per repo because their names are too generic to match by pattern.
const DATA_FILES = new Set([
  'countrypedia/script.js',
  'wayfinder/src/lib/countries-data.ts',
  'wayfinder/supabase/visa_update.sql',
]);

function isOwnCode(repo, path) {
  const ext = path.split('.').pop().toLowerCase();
  if (!CODE_EXTENSIONS.has(ext)) return false; // also drops lockfiles, images, Unity assets, JSON
  if (DATA_FILES.has(`${repo}/${path}`)) return false;
  return !EXCLUDED_PATHS.some((re) => re.test(path));
}

// GET that retries on rate limits / server errors and fails loudly instead of
// silently returning nothing (which would make the line count quietly wrong).
async function ghRetry(path) {
  for (let attempt = 1; attempt <= 5; attempt++) {
    const { status, json } = await gh(path);
    if (status === 200) return json;
    if (status !== 403 && status !== 429 && status < 500) throw new Error(`GET ${path} -> ${status}`);
    await new Promise((r) => setTimeout(r, attempt * 5000));
  }
  throw new Error(`GET ${path} kept failing`);
}

async function commitFiles(repo, sha) {
  // The commit endpoint lists 300 files per page by default (up to 3000 in total)
  const files = [];
  for (let page = 1; ; page++) {
    const json = await ghRetry(`/repos/${USER}/${repo}/commits/${sha}?page=${page}`);
    const batch = json.files ?? [];
    files.push(...batch);
    if (batch.length < 300) return { parents: json.parents?.length ?? 1, files };
  }
}

async function linesOfCode(repos) {
  let additions = 0;
  let deletions = 0;
  for (const repo of repos) {
    const shas = [];
    for (let page = 1; ; page++) {
      const { status, json } = await gh(`/repos/${USER}/${repo}/commits?author=${USER}&per_page=100&page=${page}`);
      if (status !== 200 || !Array.isArray(json) || json.length === 0) break; // empty repo or no commits
      shas.push(...json.filter((c) => c.parents.length <= 1).map((c) => c.sha)); // skip merge commits
      if (json.length < 100) break;
    }
    // fetch commit details a few at a time to keep it fast without hammering the API
    let repoAdd = 0;
    let repoDel = 0;
    for (let i = 0; i < shas.length; i += 4) {
      const details = await Promise.all(shas.slice(i, i + 4).map((sha) => commitFiles(repo, sha)));
      for (const { files } of details) {
        for (const f of files) {
          if (!isOwnCode(repo, f.filename)) continue;
          repoAdd += f.additions;
          repoDel += f.deletions;
        }
      }
    }
    additions += repoAdd;
    deletions += repoDel;
    if (process.env.LOC_DEBUG) console.log(`  ${repo}: ${shas.length} commits, +${repoAdd} -${repoDel}`);
  }
  return { additions, deletions };
}

// ---------------------------------------------------------------- profile

async function getStats() {
  const { user } = await graphql(
    `query($login: String!) {
      user(login: $login) {
        createdAt
        repositories(ownerAffiliations: OWNER, privacy: PUBLIC, isFork: false, first: 100) {
          totalCount
          nodes { name }
        }
        repositoriesContributedTo(includeUserRepositories: false, contributionTypes: [COMMIT, PULL_REQUEST]) { totalCount }
      }
    }`,
    { login: USER }
  );

  // Commits: sum yearly contribution totals since the account was created
  let commits = 0;
  const firstYear = new Date(user.createdAt).getUTCFullYear();
  for (let year = firstYear; year <= new Date().getUTCFullYear(); year++) {
    const data = await graphql(
      `query($login: String!, $from: DateTime!, $to: DateTime!) {
        user(login: $login) { contributionsCollection(from: $from, to: $to) { totalCommitContributions } }
      }`,
      { login: USER, from: `${year}-01-01T00:00:00Z`, to: `${year}-12-31T23:59:59Z` }
    );
    commits += data.user.contributionsCollection.totalCommitContributions;
  }

  const { additions, deletions } = await linesOfCode(user.repositories.nodes.map((r) => r.name));

  return {
    repos: user.repositories.totalCount,
    contributed: user.repositoriesContributedTo.totalCount,
    commits,
    additions,
    deletions,
  };
}

// ---------------------------------------------------------------- uptime

function uptime(now = new Date()) {
  let years = now.getUTCFullYear() - BIRTH.getUTCFullYear();
  let months = now.getUTCMonth() - BIRTH.getUTCMonth();
  let days = now.getUTCDate() - BIRTH.getUTCDate();
  if (days < 0) {
    months -= 1;
    days += new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), 0)).getUTCDate();
  }
  if (months < 0) {
    years -= 1;
    months += 12;
  }
  const plural = (n, word) => `${n} ${word}${n === 1 ? '' : 's'}`;
  const birthday = months === 0 && days === 0 ? ' 🎂' : '';
  return `${plural(years, 'year')}, ${plural(months, 'month')}, ${plural(days, 'day')}${birthday}`;
}

// ---------------------------------------------------------------- layout

const fmt = (n) => n.toLocaleString('en-US');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// One info line is a list of segments: [text, cssClass]. `kv` pads with dots.
const kv = (key, value, width = WIDTH) => {
  const dots = Math.max(2, width - key.length - value.length - 4);
  return [['. ', 'cc'], [key, 'key'], [':', ''], [` ${'.'.repeat(dots)} `, 'cc'], [value, 'value']];
};
const textLength = (segments) => segments.reduce((n, [text]) => n + text.length, 0);
// kv() followed by extra segments, with the dots shortened so the whole line fits WIDTH
const kvPlus = (key, value, extra) => [...kv(key, value, WIDTH - textLength(extra)), ...extra];
const header = (title) => [['— ' + title + ' ', ''], ['—'.repeat(Math.max(2, WIDTH - title.length - 3)), 'cc']];
const blank = () => [['', '']];

function infoLines(s) {
  return [
    [['victor', 'key'], ['@', ''], ['lopes', 'key'], [' ' + '—'.repeat(WIDTH - 13), 'cc']],
    kv('Uptime', uptime()),
    kv('Host', 'Universidade Politécnica de Tomar'),
    kv('Kernel', 'Software Development (2-year higher diploma)'),
    kv('Erasmus', 'Politechnika Białostocka, Poland'),
    kv('IDE', 'VS Code, IntelliJ IDEA, Unity'),
    blank(),
    kv('Languages.Programming', 'TypeScript, Java, C#, Python'),
    kv('Languages.Computer', 'HTML, CSS, SQL (PostgreSQL)'),
    kv('Languages.Real', 'Portuguese, English, Spanish'),
    kv('Stack', 'Next.js, React, Supabase, Strapi, Unity'),
    kv('Tools', 'Git, Docker, Ollama, Cisco Packet Tracer'),
    kv('Networking', 'Subnetting, VLANs, routing'),
    blank(),
    kv('Hobbies.Software', 'Web apps, Game dev'),
    kv('Hobbies.Other', 'Movies, Music, Geography'),
    kv('Before.Code', 'F&B manager · team of 35'),
    blank(),
    header('GitHub Stats'),
    kv('Repos', `${fmt(s.repos)} {Contributed: ${fmt(s.contributed)}}`),
    kv('Commits', fmt(s.commits)),
    kvPlus('Lines of Code', fmt(s.additions - s.deletions), [
      [' ( ', ''], [fmt(s.additions) + '++', 'add'], [', ', ''], [fmt(s.deletions) + '--', 'del'], [' )', ''],
    ]),
  ];
}

const THEMES = {
  // GitHub dark palette
  dark: { bg: '#161b22', border: '#30363d', text: '#c9d1d9', key: '#ffa657', value: '#a5d6ff', cc: '#6e7681', add: '#3fb950', del: '#f85149' },
  // GitHub light palette: dark text on white, colours picked for contrast on a light background
  light: { bg: '#ffffff', border: '#d0d7de', text: '#1f2328', key: '#bc4c00', value: '#0550ae', cc: '#8c959f', add: '#1a7f37', del: '#cf222e' },
};

function svg(theme, lines) {
  const t = THEMES[theme];
  // kv lines are WIDTH + 1 characters long (". " prefix and the spaces around the dots)
  const cardW = Math.round(PAD * 2 + (WIDTH + 1) * CHAR_W);
  const top = PAD + FONT_SIZE;
  const height = top + (lines.length - 1) * LINE_H + PAD;

  const infoSvg = lines
    .map((segments, i) => {
      const spans = segments.map(([text, cls]) => (cls ? `<tspan class="${cls}">${esc(text)}</tspan>` : esc(text))).join('');
      return `<tspan x="${PAD}" y="${top + i * LINE_H}">${spans}</tspan>`;
    })
    .join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" font-family="ConsolasFallback,Consolas,'Courier New',monospace" width="${cardW}px" height="${height}px" font-size="${FONT_SIZE}px">
<style>
.key { fill: ${t.key}; } .value { fill: ${t.value}; } .cc { fill: ${t.cc}; }
.add { fill: ${t.add}; } .del { fill: ${t.del}; }
text, tspan { white-space: pre; }
</style>
<rect x="0.5" y="0.5" width="${cardW - 1}px" height="${height - 1}px" fill="${t.bg}" stroke="${t.border}" rx="15"/>
<text x="${PAD}" y="${top}" fill="${t.text}">
${infoSvg}
</text>
</svg>
`;
}

// ---------------------------------------------------------------- main

if (!TOKEN) throw new Error('Set GH_TOKEN (or GITHUB_TOKEN) to read GitHub stats.');
const stats = await getStats();
const lines = infoLines(stats);
for (const theme of ['dark', 'light']) {
  writeFileSync(new URL(`../${theme}_mode.svg`, import.meta.url), svg(theme, lines));
}
console.log('Built cards:', JSON.stringify(stats), '| uptime:', uptime());
